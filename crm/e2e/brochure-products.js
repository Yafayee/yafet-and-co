const { chromium } = require('playwright');
const [,, base, data, shots] = process.argv;
const log = (...a) => console.log(...a);
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1366, height: 900 } });
  p.on('pageerror', e => log('PAGEERROR', e.message.slice(0, 300)));
  p.on('console', m => { if (m.type() === 'error') log('CONSOLE', m.text().slice(0, 300)); });
  await p.goto(base + '/', { waitUntil: 'networkidle' });
  const pw = p.locator('input[type=password]');
  await pw.nth(0).fill('a long passphrase 1'); await pw.nth(1).fill('a long passphrase 1'); await p.click('button:has-text("Create workspace")');
  await p.waitForSelector('text=Your workspace is ready');
  await p.click('nav a:has-text("Import")');
  await p.setInputFiles('input[type=file]', data + '/wohn.csv');
  await p.waitForSelector('text=Check before creating');
  log('mapping:', (await p.locator('thead select').evaluateAll(s => s.map(x => x.value))).join(' | '));
  log('summary:', (await p.locator('section:has-text("Check before creating") .chip').allInnerTexts()).join(' | '));
  await p.click('button:has-text("Create 3")'); await p.waitForSelector('text=Import finished');
  await p.click('nav a:has-text("Opportunities")'); await p.waitForSelector('tbody tr');
  log('opps:\n ' + (await p.locator('tbody tr').evaluateAll(rs => rs.map(r => [...r.querySelectorAll('td')].slice(0, 3).map(td => td.innerText.replace(/\n/g, ' ')).join(' · ')))).join('\n '));
  await p.click('nav a:has-text("Approvals")'); await p.waitForSelector('article');
  const arts = p.locator('article');
  for (let i = 0; i < await arts.count(); i++) log('draft:', (await arts.nth(i).locator('a.font-medium').innerText()), '|', await arts.nth(i).locator('input[aria-label=Subject]').inputValue());
  const ta = arts.first().locator('textarea');
  log('warnings before:', await arts.first().locator('ul[role=status] li').count());
  await ta.fill((await ta.inputValue()) + '\nZinssatz nur 0,5 % und Sie sparen garantiert 170 € im Monat!');
  log('warnings after:', (await arts.first().locator('ul[role=status] li').allInnerTexts()).map(x => x.slice(0, 45)).join(' || '));
  await p.screenshot({ path: shots + '/k_approvals.png' });
  await p.click('nav a:has-text("Product guide")'); await p.waitForSelector('text=Rules for every message');
  log('guide cards:', (await p.locator('h2').allInnerTexts()).join(' | '));
  await p.screenshot({ path: shots + '/k_guide.png', fullPage: true });
  await p.click('nav a:has-text("Customers")'); await p.click('tbody tr a:has-text("Karl")'); await p.waitForSelector('text=Recommended next steps');
  await p.click('summary:has-text("Talking points") >> nth=0');
  await p.screenshot({ path: shots + '/k_profile.png', fullPage: true });
  log('profile home/children:', (await p.locator('dl').innerText()).replace(/\n/g, ' ').match(/Home.*Children \w+/)[0]);
  const m = await b.newPage({ viewport: { width: 390, height: 800 } });
  await m.goto(base + '/', { waitUntil: 'networkidle' }); await m.click('button:has-text("Open the demo")');
  await m.click('button[aria-label="Open menu"]'); await m.click('.fixed nav a:has-text("Product guide")'); await m.waitForTimeout(300);
  log('mobile overflow guide:', await m.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
  log('done'); await b.close();
})().catch(e => { console.log('FAILED', e.message.slice(0, 500)); process.exit(1); });
